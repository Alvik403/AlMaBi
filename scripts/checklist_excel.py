"""Shared Excel builder for AlMaBi checklists."""

from __future__ import annotations

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

HEADER_FILL = PatternFill("solid", fgColor="1E3A5F")
HEADER_FONT = Font(bold=True, color="FFFFFF", size=11)
THIN = Side(style="thin", color="CBD5E1")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _style_header(ws: Worksheet, headers: list[str], widths: list[int]) -> None:
    for col, title in enumerate(headers, 1):
        cell = ws.cell(row=1, column=col, value=title)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.freeze_panes = "A2"
    ws.row_dimensions[1].height = 30
    for col, width in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(col)].width = width


def _write_rows(ws: Worksheet, headers_count: int, rows: list[tuple], *, extra_blank: int = 10) -> None:
    row_idx = 1
    for index, values in enumerate(rows, 1):
        row_idx = index + 1
        row_values = (index, *values)
        for col, value in enumerate(row_values, 1):
            cell = ws.cell(row=row_idx, column=col, value=value)
            cell.border = BORDER
            cell.alignment = Alignment(vertical="top", wrap_text=True)

    for extra in range(1, extra_blank + 1):
        row_idx += 1
        ws.cell(row=row_idx, column=1, value=len(rows) + extra).border = BORDER
        for col in range(2, headers_count + 1):
            cell = ws.cell(row=row_idx, column=col, value=None)
            cell.border = BORDER
            cell.alignment = Alignment(vertical="top", wrap_text=True)


